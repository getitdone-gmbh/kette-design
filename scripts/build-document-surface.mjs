// Generates styles/document-surface.css: re-applies the light value of every token the `.dark` scope overrides,
// scoped to the DocumentSurface paper, so a white page keeps light colours inside a dark app.
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(new URL('../styles/theme.css', import.meta.url), 'utf8');

const block = (selector) => {
  const start = source.indexOf(`\n${selector} {`);
  if (start === -1) throw new Error(`Selector not found: ${selector}`);
  const end = source.indexOf('\n}', start);
  return source.slice(start, end);
};
const declarations = (css) => new Map([...css.matchAll(/^\s*(--[\w-]+):\s*(.+?);\s*$/gm)].map((m) => [m[1], m[2]]));

const light = declarations(block(':root'));
const dark = declarations(block('.dark'));
const lines = [...dark.keys()].filter((name) => light.has(name)).map((name) => `  ${name}: ${light.get(name)};`);

writeFileSync(
  new URL('../styles/document-surface.css', import.meta.url),
  `/* Generated by scripts/build-document-surface.mjs from styles/theme.css. Do not edit. */\n[data-document-surface] {\n  color-scheme: light;\n${lines.join('\n')}\n}\n`,
);
console.log(`document-surface.css: ${lines.length} tokens`);
